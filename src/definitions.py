from dataclasses import dataclass
from enum import Enum


class TokenType(Enum):
    KEYWORD = 1
    ID = 2
    SYMBOL = 3
    OPERATOR = 4
    NUMBER = 5


@dataclass
class Token:
    code: TokenType
    val: str | int

    def __repr__(self):
        return f"<{self.code.name}, {self.val}>"


